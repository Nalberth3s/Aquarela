/** Frequência mensal por aluno (gerada de forma determinística para a demo). */
export function buildAttendanceMock(studentId: string): AttendanceRecord[] {
  const seed = Number(studentId.replace(/\D/g, '')) || 1
  const months = [
    { month: 'Maio', schoolDays: 21 },
    { month: 'Junho', schoolDays: 20 },
    { month: 'Julho', schoolDays: 10 },
    { month: 'Agosto', schoolDays: 21 },
    { month: 'Setembro', schoolDays: 18 },
  ]
  return months.map((m, i) => ({
    ...m,
    present: Math.max(m.schoolDays - ((seed + i * 3) % 3), 0),
  }))
}
